// ShotLightbox.astro, emitted into the Starlight site: the one tap-to-enlarge component. It renders
// no markup of its own. Any `a[data-docsx-zoom]` that wraps an <img> becomes its trigger, so
// AnnotatedShot uses it and any later image can opt in with the same attribute.
//
// Without JS the trigger is a plain link to the image file, which the browser opens full size
// and the reader can pinch-zoom. With JS the script gives each trigger button semantics (Enter and
// Space open it; a modified click still opens the file in a new tab) and opens one shared <dialog>
// built on first use: the image at its native pixel size in a scroll frame, pannable both ways and
// pinch-zoomable, with a 44 px Close button inside the safe area. Escape, Close, a tap on the
// backdrop around the image and a drag down on touch (when the frame is scrolled to the top and the
// page is not pinch-zoomed) all close it; focus stays inside while it is open and returns to the
// trigger afterwards. Colours are Starlight's theme variables. The only motion, a fade in and the
// snap back of a cancelled drag, runs under prefers-reduced-motion: no-preference.

import { jsString, type UiStrings } from "./ui-strings.js";

/** A drag down past this many CSS px closes the dialog; a shorter one snaps back. */
export const DISMISS_DRAG_PX = 96;

export function shotLightboxAstro(ui: UiStrings): string {
  return `---
// Generated by docsxai, the tap-to-enlarge lightbox for screenshots. Renders no markup: it adds
// the shared style and script once per page for every a[data-docsx-zoom] trigger.
---

<style is:global>
  .docsx-zoom {
    position: relative;
    display: block;
    width: fit-content;
    max-width: 100%;
    min-width: 44px;
    min-height: 44px;
    color: inherit;
    border-radius: 0.5rem;
    cursor: zoom-in;
  }
  .docsx-zoom:focus-visible {
    outline: 3px solid var(--sl-color-white);
    outline-offset: 2px;
  }
  .docsx-zoom-hint {
    position: absolute;
    right: 0.5rem;
    bottom: 0.5rem;
    display: none;
    align-items: center;
    gap: 0.25rem;
    padding: 0.25rem 0.5rem;
    font-size: var(--sl-text-xs);
    line-height: 1.2;
    color: var(--sl-color-text);
    background: var(--sl-color-bg);
    border: 1px solid var(--sl-color-gray-5);
    border-radius: 0.375rem;
    pointer-events: none;
  }
  .docsx-zoom-hint svg {
    width: 1em;
    height: 1em;
  }
  .docsx-zoom:hover .docsx-zoom-hint,
  .docsx-zoom:focus-visible .docsx-zoom-hint {
    display: inline-flex;
  }
  @media (hover: none), (max-width: 50rem) {
    .docsx-zoom-hint {
      display: inline-flex;
    }
  }
  .docsx-lightbox {
    box-sizing: border-box;
    width: 100%;
    max-width: none;
    height: 100%;
    max-height: none;
    margin: 0;
    padding: 0;
    color: var(--sl-color-text);
    background: var(--sl-color-bg);
    border: 0;
    overflow: hidden;
  }
  .docsx-lightbox::backdrop {
    background: var(--sl-color-bg);
  }
  .docsx-lightbox-frame {
    box-sizing: border-box;
    display: flex;
    width: 100%;
    height: 100%;
    padding: calc(env(safe-area-inset-top, 0px) + 3.75rem) calc(env(safe-area-inset-right, 0px) + 0.5rem)
      calc(env(safe-area-inset-bottom, 0px) + 0.5rem) calc(env(safe-area-inset-left, 0px) + 0.5rem);
    overflow: auto;
    overscroll-behavior: contain;
    touch-action: pan-x pan-y pinch-zoom;
  }
  .docsx-lightbox-frame:focus-visible {
    outline: 3px solid var(--sl-color-white);
    outline-offset: -3px;
  }
  .docsx-lightbox-img {
    flex: none;
    max-width: none;
    height: auto;
    margin: auto;
    background: var(--sl-color-gray-6);
  }
  .docsx-lightbox-close {
    position: absolute;
    top: calc(env(safe-area-inset-top, 0px) + 0.5rem);
    right: calc(env(safe-area-inset-right, 0px) + 0.5rem);
    z-index: 1;
    display: inline-flex;
    align-items: center;
    justify-content: center;
    gap: 0.25rem;
    min-width: 44px;
    min-height: 44px;
    padding: 0 0.75rem;
    font: inherit;
    font-size: var(--sl-text-sm);
    color: var(--sl-color-text);
    background: var(--sl-color-bg);
    border: 1px solid var(--sl-color-text);
    border-radius: 0.375rem;
    cursor: pointer;
  }
  .docsx-lightbox-close:hover {
    background: var(--sl-color-gray-6);
  }
  .docsx-lightbox-close:active {
    background: var(--sl-color-gray-5);
  }
  .docsx-lightbox-close:focus-visible {
    outline: 3px solid var(--sl-color-white);
    outline-offset: 2px;
  }
  @media (prefers-reduced-motion: no-preference) {
    .docsx-lightbox[open] {
      animation: docsx-lightbox-in 160ms ease-out;
    }
    .docsx-lightbox-frame.is-settling {
      transition: transform 160ms ease-out;
    }
  }
  @keyframes docsx-lightbox-in {
    from {
      opacity: 0;
    }
  }
</style>

<script>
  const DISMISS_PX = ${DISMISS_DRAG_PX};
  let dialog = null;
  let frame = null;
  let big = null;
  let closeBtn = null;
  let opener = null;
  let drag = null;

  function supported() {
    return typeof HTMLDialogElement === "function" && "showModal" in HTMLDialogElement.prototype;
  }

  function close() {
    if (!dialog || !dialog.open) return;
    dialog.close();
    frame.style.transform = "";
    big.removeAttribute("src");
    const back = opener;
    opener = null;
    if (back && back.isConnected) back.focus();
  }

  function trapTab(e) {
    if (e.key !== "Tab") return;
    const stops = [closeBtn, frame];
    const i = stops.indexOf(document.activeElement);
    const next = e.shiftKey ? (i <= 0 ? stops.length - 1 : i - 1) : (i + 1) % stops.length;
    stops[next].focus();
    e.preventDefault();
  }

  // A drag down by one finger closes the dialog when the frame is at its top and the page is not
  // pinch-zoomed; the frame follows the finger meanwhile. Anything else is a pan or a pinch.
  function pinchZoomed() {
    return !!window.visualViewport && window.visualViewport.scale > 1.01;
  }
  function onTouchStart(e) {
    drag = null;
    if (e.touches.length !== 1 || frame.scrollTop > 0 || pinchZoomed()) return;
    drag = { x: e.touches[0].clientX, y: e.touches[0].clientY, dy: 0, on: false };
    frame.classList.remove("is-settling");
  }
  function onTouchMove(e) {
    if (!drag) return;
    if (e.touches.length !== 1 || pinchZoomed()) {
      drag = null;
      frame.style.transform = "";
      return;
    }
    const dx = e.touches[0].clientX - drag.x;
    const dy = e.touches[0].clientY - drag.y;
    if (!drag.on && (dy <= 0 || Math.abs(dx) > dy)) {
      drag = null;
      return;
    }
    drag.on = true;
    drag.dy = Math.max(0, dy);
    frame.style.transform = "translateY(" + drag.dy + "px)";
  }
  function onTouchEnd() {
    if (!drag) return;
    const done = drag.on && drag.dy >= DISMISS_PX;
    drag = null;
    if (done) return close();
    frame.classList.add("is-settling");
    frame.style.transform = "";
  }

  function build() {
    dialog = document.createElement("dialog");
    dialog.className = "docsx-lightbox";
    dialog.setAttribute("aria-label", ${jsString(ui.site.zoomDialog)});
    frame = document.createElement("div");
    frame.className = "docsx-lightbox-frame";
    frame.tabIndex = 0;
    big = document.createElement("img");
    big.className = "docsx-lightbox-img";
    big.decoding = "async";
    closeBtn = document.createElement("button");
    closeBtn.type = "button";
    closeBtn.className = "docsx-lightbox-close";
    closeBtn.textContent = ${jsString(ui.site.zoomClose)};
    frame.appendChild(big);
    dialog.append(closeBtn, frame);
    closeBtn.addEventListener("click", close);
    dialog.addEventListener("cancel", (e) => {
      e.preventDefault();
      close();
    });
    dialog.addEventListener("keydown", trapTab);
    // A tap on the space around the image (the frame or the dialog itself) closes it.
    dialog.addEventListener("click", (e) => {
      if (e.target === dialog || e.target === frame) close();
    });
    frame.addEventListener("touchstart", onTouchStart, { passive: true });
    frame.addEventListener("touchmove", onTouchMove, { passive: true });
    frame.addEventListener("touchend", onTouchEnd);
    frame.addEventListener("touchcancel", onTouchEnd);
    document.body.appendChild(dialog);
  }

  function open(link) {
    const thumb = link.querySelector("img");
    if (!dialog) build();
    opener = link;
    big.alt = thumb ? thumb.alt : "";
    const w = thumb && (thumb.naturalWidth || Number(thumb.getAttribute("width")));
    const h = thumb && (thumb.naturalHeight || Number(thumb.getAttribute("height")));
    if (w && h) {
      big.width = w;
      big.height = h;
    } else {
      big.removeAttribute("width");
      big.removeAttribute("height");
    }
    big.src = link.getAttribute("href") || (thumb && thumb.currentSrc) || "";
    frame.style.transform = "";
    dialog.showModal();
    frame.scrollTop = 0;
    frame.scrollLeft = 0;
    closeBtn.focus();
  }

  function trigger(target) {
    return target && target.closest ? target.closest("a[data-docsx-zoom]") : null;
  }

  if (supported()) {
    for (const link of Array.from(document.querySelectorAll("a[data-docsx-zoom]")))
      link.setAttribute("role", "button");
    document.addEventListener("click", (e) => {
      const link = trigger(e.target);
      if (!link || e.button !== 0 || e.metaKey || e.ctrlKey || e.shiftKey || e.altKey) return;
      e.preventDefault();
      open(link);
    });
    document.addEventListener("keydown", (e) => {
      if (e.key !== " " && e.key !== "Spacebar") return;
      const link = trigger(e.target);
      if (!link) return;
      e.preventDefault();
      open(link);
    });
  }
</script>
`;
}
