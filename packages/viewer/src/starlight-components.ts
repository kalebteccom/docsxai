// Copy button for an id or a command. The script is bundled once by Astro however many buttons
// the page holds, and listens on the document. The three labels share one grid cell, so the widest
// ("Press Ctrl+C") sets the button's width and no state moves the page. The accessible name stays
// "Copy <kind> <value>"; the state is spoken through the button's own polite status span. Without
// navigator.clipboard the id text is selected and the button asks for Ctrl+C. Colours come from
// Starlight's theme variables, so both themes are covered. No animation or transition.
export const COPY_ID_ASTRO = `---
// Generated by docsxai, copy-to-clipboard button for an id or a command.
const { value, kind = "id" } = Astro.props;
---

<span class="docsx-copyable">
  <code class="docsx-id">{value}</code>
  <button
    type="button"
    class="docsx-copy"
    data-copy={value}
    data-kind={kind}
    data-state="idle"
    aria-label={\`Copy \${kind} \${value}\`}
  >
    <span class="docsx-copy-label docsx-copy-idle" aria-hidden="true">Copy</span>
    <span class="docsx-copy-label docsx-copy-done" aria-hidden="true">Copied</span>
    <span class="docsx-copy-label docsx-copy-fallback" aria-hidden="true">Press Ctrl+C</span>
  </button>
  <span class="docsx-live" role="status" aria-live="polite" aria-atomic="true"></span>
</span>

<style is:global>
  .docsx-copyable {
    display: inline-flex;
    flex-wrap: wrap;
    align-items: center;
    gap: 0.25rem 0.5rem;
  }
  .docsx-id {
    overflow-wrap: anywhere;
  }
  .docsx-copy {
    display: inline-grid;
    place-items: center;
    min-width: 44px;
    min-height: 44px;
    padding: 0 0.75rem;
    font: inherit;
    font-size: var(--sl-text-sm);
    color: var(--sl-color-text);
    background: var(--sl-color-bg);
    border: 1px solid var(--sl-color-text);
    border-radius: 0.375rem;
    cursor: pointer;
  }
  .docsx-copy:hover {
    background: var(--sl-color-gray-6);
  }
  .docsx-copy:focus-visible {
    outline: 3px solid var(--sl-color-text-accent);
    outline-offset: 2px;
  }
  .docsx-copy[data-state="done"] {
    background: var(--sl-color-gray-5);
  }
  .docsx-copy-label {
    grid-area: 1 / 1;
    visibility: hidden;
    white-space: nowrap;
  }
  .docsx-copy[data-state="idle"] .docsx-copy-idle,
  .docsx-copy[data-state="done"] .docsx-copy-done,
  .docsx-copy[data-state="fallback"] .docsx-copy-fallback {
    visibility: visible;
  }
  .docsx-live {
    position: absolute;
    width: 1px;
    height: 1px;
    margin: -1px;
    padding: 0;
    overflow: hidden;
    clip: rect(0 0 0 0);
    white-space: nowrap;
    border: 0;
  }
</style>

<script>
  const COPIED_MS = 1500;
  const FALLBACK_MS = 5000;
  const timers = new Map();

  function announce(btn, text) {
    const live = btn.parentElement && btn.parentElement.querySelector(".docsx-live");
    if (!live) return;
    live.textContent = "";
    window.setTimeout(() => {
      live.textContent = text;
    }, 50);
  }

  function show(btn, state, ms) {
    const kind = btn.getAttribute("data-kind") || "id";
    const value = btn.getAttribute("data-copy") || "";
    btn.setAttribute("data-state", state);
    announce(
      btn,
      state === "done"
        ? "Copied " + kind + " " + value + " to the clipboard."
        : "The clipboard is not available here. The " + kind + " is selected, press Ctrl+C (Cmd+C on a Mac) to copy it.",
    );
    window.clearTimeout(timers.get(btn));
    timers.set(
      btn,
      window.setTimeout(() => btn.setAttribute("data-state", "idle"), ms),
    );
  }

  function fallback(btn) {
    const id = btn.parentElement && btn.parentElement.querySelector(".docsx-id");
    const sel = window.getSelection();
    if (id && sel) {
      const range = document.createRange();
      range.selectNodeContents(id);
      sel.removeAllRanges();
      sel.addRange(range);
    }
    show(btn, "fallback", FALLBACK_MS);
  }

  document.addEventListener("click", (e) => {
    const target = e.target;
    const btn = target && target.closest ? target.closest("button.docsx-copy") : null;
    if (!btn) return;
    const clip = navigator.clipboard;
    if (!clip || typeof clip.writeText !== "function") return fallback(btn);
    clip.writeText(btn.getAttribute("data-copy") || "").then(
      () => show(btn, "done", COPIED_MS),
      () => fallback(btn),
    );
  });
</script>
`;

// The caption list is numbered to match the badge numbers burned into the image (`item.n` is the
// annotation's 1-based badge index), so <li value> carries the explicit number. The image carries
// its intrinsic width and height (Astro reads them from the imported file), so its box is reserved
// before it loads. A failed load shows a message with Retry (a fresh query string defeats a cached
// failure), and a step with no image shows why and the command that captures it.
export const ANNOTATED_SHOT_ASTRO = `---
// Generated by docsxai — annotated screenshot figure.
// The image already carries the burned halo/badge/callout pixels when burned={true}; the caption
// lists each annotation's copy, numbered to match the burned badges.
import CopyId from "./CopyId.astro";
const { src, alt, items = [], burned = false, missing = false, flow = "" } = Astro.props;
const resolved = src === undefined ? "" : typeof src === "string" ? src : src.src;
const width = src && typeof src === "object" ? src.width : undefined;
const height = src && typeof src === "object" ? src.height : undefined;
const command = \`docsxai run <workspace>\${flow ? \` --flow \${flow.split("/")[0]}\` : ""} --start-from \${alt}\`;
---

<figure class="annotated-shot" data-burned={burned ? "true" : "false"}>
  {
    missing ? (
      <div class="annotated-shot-missing" role="status">
        <p>
          No screenshot for step <code>{alt}</code>. The file was not found when this site was built.
        </p>
        <p>
          Capture it with <CopyId value={command} kind="command" /> then build the site again.
        </p>
      </div>
    ) : (
      <>
        <img
          src={resolved}
          alt={alt}
          width={width}
          height={height}
          loading="lazy"
          decoding="async"
        />
        <p class="annotated-shot-error" role="alert" hidden>
          <span class="annotated-shot-error-msg">
            The screenshot for step {alt} could not be loaded. Check your connection, then press Retry.
          </span>
          <button type="button" class="annotated-shot-retry">Retry</button>
        </p>
      </>
    )
  }
  {items.length === 1 && <figcaption>{items[0].copy}</figcaption>}
  {
    items.length > 1 && (
      <figcaption>
        <ol>
          {items.map((item) => (
            <li value={item.n}>{item.copy}</li>
          ))}
        </ol>
      </figcaption>
    )
  }
  <p class="annotated-shot-id">Step id <CopyId value={alt} kind="step id" /></p>
</figure>

<style>
  .annotated-shot {
    margin: 1.5rem 0;
  }
  .annotated-shot img {
    display: block;
    max-width: 100%;
    height: auto;
    background: var(--sl-color-gray-6);
    border: 1px solid var(--sl-color-gray-5);
    border-radius: 0.5rem;
  }
  .annotated-shot img.is-broken {
    border-color: var(--sl-color-text-accent);
  }
  .annotated-shot-missing {
    box-sizing: border-box;
    min-height: 160px;
    display: grid;
    align-content: center;
    padding: 2rem 1rem;
    text-align: center;
    color: var(--sl-color-gray-2);
    background: var(--sl-color-gray-6);
    border: 1px dashed var(--sl-color-gray-3);
    border-radius: 0.5rem;
  }
  .annotated-shot-missing p {
    margin: 0.25rem 0;
  }
  .annotated-shot-error {
    margin: 0.5rem 0 0;
    color: var(--sl-color-text);
  }
  .annotated-shot-error[hidden] {
    display: none;
  }
  .annotated-shot-retry {
    box-sizing: border-box;
    width: 10ch;
    min-width: 44px;
    min-height: 44px;
    padding: 0.25rem 0.75rem;
    font: inherit;
    color: var(--sl-color-text);
    background: var(--sl-color-bg);
    border: 1px solid var(--sl-color-text);
    border-radius: 0.375rem;
    cursor: pointer;
  }
  .annotated-shot-retry[aria-disabled="true"] {
    background: var(--sl-color-gray-5);
    cursor: progress;
  }
  .annotated-shot-retry:focus-visible {
    outline: 3px solid var(--sl-color-text-accent);
    outline-offset: 2px;
  }
  .annotated-shot figcaption {
    margin-top: 0.5rem;
    color: var(--sl-color-gray-2);
    font-size: var(--sl-text-sm);
  }
  .annotated-shot ol {
    margin: 0;
    padding-inline-start: 1.5rem;
  }
  .annotated-shot li {
    margin: 0.15rem 0;
  }
  .annotated-shot-id {
    margin: 0.25rem 0 0;
    color: var(--sl-color-gray-2);
    font-size: var(--sl-text-sm);
  }
</style>

<script>
  // Retry for a screenshot that failed to load: error events do not bubble, so listen in the
  // capture phase. Images that failed before this script ran are caught by the sweep below.
  function figureOf(img) {
    return img.closest(".annotated-shot");
  }
  function fail(img) {
    const fig = figureOf(img);
    const box = fig && fig.querySelector(".annotated-shot-error");
    img.classList.add("is-broken");
    if (!box) return;
    box.hidden = false;
    const btn = box.querySelector("button");
    if (btn) {
      btn.removeAttribute("aria-disabled");
      btn.textContent = "Retry";
    }
    const tries = Number(img.getAttribute("data-tries") || "0");
    const msg = box.querySelector(".annotated-shot-error-msg");
    if (msg && tries > 0 && !msg.getAttribute("data-base"))
      msg.setAttribute("data-base", msg.textContent || "");
    if (msg && tries > 0)
      msg.textContent =
        "Still not loading after " + tries + (tries === 1 ? " try. " : " tries. ") + msg.getAttribute("data-base");
  }
  function ok(img) {
    const fig = figureOf(img);
    const box = fig && fig.querySelector(".annotated-shot-error");
    img.classList.remove("is-broken");
    if (box) box.hidden = true;
  }
  document.addEventListener(
    "error",
    (e) => {
      const t = e.target;
      if (t && t.tagName === "IMG" && figureOf(t)) fail(t);
    },
    true,
  );
  document.addEventListener(
    "load",
    (e) => {
      const t = e.target;
      if (t && t.tagName === "IMG" && figureOf(t)) ok(t);
    },
    true,
  );
  document.addEventListener("click", (e) => {
    const target = e.target;
    const btn = target && target.closest ? target.closest("button.annotated-shot-retry") : null;
    if (!btn || btn.getAttribute("aria-disabled") === "true") return;
    const fig = btn.closest(".annotated-shot");
    const img = fig && fig.querySelector("img");
    if (!img) return;
    const tries = Number(img.getAttribute("data-tries") || "0") + 1;
    if (!img.getAttribute("data-src")) img.setAttribute("data-src", img.getAttribute("src") || "");
    const base = img.getAttribute("data-src") || "";
    img.setAttribute("data-tries", String(tries));
    btn.setAttribute("aria-disabled", "true");
    btn.textContent = "Retrying\\u2026";
    img.src = base + (base.indexOf("?") >= 0 ? "&" : "?") + "retry=" + tries;
  });
  for (const img of Array.from(document.querySelectorAll(".annotated-shot img"))) {
    if (img.complete && !img.naturalWidth && img.getAttribute("src")) fail(img);
  }
</script>
`;
